import { test, expect } from '@playwright/test'
const source = (name: string, data: unknown, status='available') => ({name,data,status,classification:'test',sourceUrl:'https://www.census.gov',vintage:'2024 ACS',retrievedAt:'2026-11-07T18:00:00Z',error:status==='available'?null:'Population source unavailable'})
const feature = (id: string, name: string, x: number) => ({type:'Feature',id,properties:{NAME:name,GEOID:id},geometry:{type:'Polygon',coordinates:[[[x,29],[x+1,29],[x+1,30],[x,30],[x,29]]]}})
const alert = (id: string, event: string, severity: string, countyIds: string[]) => ({id,event,severity,countyIds,area:countyIds.includes('48201')?'Harris County':'Galveston County',headline:null,description:'Source event description',instruction:'Follow official instructions',sent:'2026-11-07T18:00:00Z',expires:'2099-01-01T00:00:00Z',effective:null,ends:null,geometry:null,urgency:'Immediate',certainty:'Observed',sourceUrl:'https://www.weather.gov/alerts'})
const stateData = {state:'TX',generatedAt:'2026-11-07',sources:{
 noaa:source('NWS',{alerts:[alert('minor','Wind Advisory','Minor',['48167']),alert('severe','Flood Warning','Severe',['48201']),alert('no-county','Marine Warning','Moderate',[])],truncated:false,updated:null}),
 earthquakes:source('USGS',{events:[],window:'24 hours',generated:null}),
 boundaries:source('Census boundaries',{type:'FeatureCollection',features:[feature('48201','Harris County',-96),feature('48167','Galveston County',-95)]}),
 fema:source('FEMA',{records:[],limit:100,truncated:false}),nri:source('NRI',{counties:[]})}}
const metric = (estimate: number) => ({estimate,marginOfError:20,variable:'test'})
function countyData(id: string) {return {countyId:id,generatedAt:'2026-11-07',sources:{acs:source('Census ACS',{countyId:id,name:id==='48201'?'Harris County, Texas':'Galveston County, Texas',period:'2020-2024',population:metric(id==='48201'?1000:500),households:metric(200),noVehicleHouseholds:metric(20),noInternetHouseholds:metric(40),vehicleUniverse:metric(200),internetUniverse:metric(200),noVehiclePercent:10,noInternetPercent:20,povertyPercent:15,ageGroups:{total:id==='48201'?1000:500,children:id==='48201'?200:100,adults:id==='48201'?650:325,olderAdults:id==='48201'?150:75}}),fema:stateData.sources.fema,nri:stateData.sources.nri}}}
async function mock(page: import('@playwright/test').Page) {
 await page.route('**/api/public/state/TX',route=>route.fulfill({json:stateData}))
 await page.route('**/api/public/county/*',route=>route.fulfill({json:countyData(route.request().url().split('/').pop()!)}))
}
