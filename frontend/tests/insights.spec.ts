test('optional county filter narrows events and resets when changing state',async({page})=>{
 await mock(page)
 await page.route('**/api/public/state/CA',route=>route.fulfill({json:{...stateData,state:'CA'}}))
 await page.goto('/insights')
 const counties=page.getByRole('combobox',{name:'County (optional)',exact:true})
 await expect(counties).toBeEnabled()
 await counties.selectOption('48167')
 await expect(page.locator('.insights-event')).toHaveCount(1)
 await expect(page.locator('.insights-selected h2')).toHaveText('Wind Advisory')
 await expect(page.locator('.insights-county-map path.chosen')).toHaveAttribute('aria-label','View Galveston County population')
 await expect(page.locator('.insights-population')).toContainText('500')
 await counties.selectOption('')
 await expect(page.locator('.insights-event')).toHaveCount(3)
 await counties.selectOption('48201')
 await expect(page.locator('.insights-event')).toHaveCount(1)
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByLabel('Explore a state',{exact:true}).selectOption('CA')
 await expect(counties).toHaveValue('')
 await expect(page.locator('.insights-event')).toHaveCount(3)
 await page.getByLabel('Explore a state',{exact:true}).selectOption('ALL')
 await expect(counties).toBeDisabled()
 await expect(counties).toHaveValue('')
})

