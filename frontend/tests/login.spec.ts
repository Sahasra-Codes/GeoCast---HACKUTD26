import { test, expect } from '@playwright/test'
test('login UI handles unconfigured auth and password visibility', async ({ page }) => {
  await page.goto('/login')
  await expect(page.getByRole('heading', { name: 'Good to see you.' })).toBeVisible()
  await page.getByLabel('Email address').fill('demo@example.com')
  await page.getByLabel('Password', { exact: true }).fill('example-password')
  await page.getByRole('button', { name: 'Show password' }).click()
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type','text')
  await page.getByRole('button', { name: 'Hide password' }).click()
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type','password')
  await expect(page.getByRole('alert')).toContainText('Configure the Supabase project URL')
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeDisabled()
  await page.screenshot({ path: 'test-results/geocast-login.png', fullPage:true })
  await page.setViewportSize({ width:390,height:844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('link', { name:'Explore the demo' }).last().click()
  await expect(page.getByRole('link', { name:'State Farm GeoCast home' })).toBeVisible()
})
