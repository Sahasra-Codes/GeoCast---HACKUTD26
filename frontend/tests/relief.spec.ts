import {test,expect} from '@playwright/test'
test.use({launchOptions:{args:[]}})
const alert=(id:string,event:string,severity:string,area:string,state:string)=>({id,event,severity,area,stateCodes:[state],countyIds:[],urgency:'Immediate',certainty:'Observed',headline:id,description:'* WHAT...Moderate flooding is occurring.\n* IMPACTS...Low roads are flooded.',instruction:'Follow official instructions.',sent:'2026-11-07T20:00:00Z',expires:'2099-01-01T00:00:00Z',sourceUrl:'https://www.weather.gov/alerts'})
const alerts=[alert('fl-minor','Flood Advisory','Minor','Florida county A','FL'),alert('tx-wind','High Wind Warning','Extreme','Texas county','TX'),alert('fl-severe','Flood Warning','Severe','Florida county B','FL')]
test('Relief filters nationwide alerts by disaster tags and area, ranks severity and requests a scoped plan',async({page})=>{
 await page.route('**/api/public/alerts',r=>r.fulfill({json:{status:'available',data:{alerts,truncated:false},retrievedAt:'2026-11-07T20:00:00Z'}}))
 let input:{alertIds:string[];request:string}|undefined
 await page.route('**/api/relief/plan',async r=>{input=r.request().postDataJSON();await r.fulfill({json:{id:'test-plan',title:'Florida flooding plan',text:'1. Executive summary\nThis is a test response, not a real plan.\n2. First six hours\nVerify local conditions.',generatedAt:'2026-11-07T20:00:00Z',source:'gemini',model:'test',draft:true,alerts:alerts.filter(a=>a.stateCodes.includes('FL'))}})})
 await page.goto('/relief',{waitUntil:'domcontentloaded'})
 const events=page.locator('.relief-event')
 await expect(events).toHaveCount(3)
 await expect(events.first()).toContainText('High Wind Warning')
 await page.getByRole('button',{name:'Floods',exact:true}).click()
 await page.getByLabel('Relief area',{exact:true}).selectOption('FL')
 await expect(events).toHaveCount(2)
 await expect(events.first()).toContainText('Flood Warning')
 await page.getByLabel('Relief severity',{exact:true}).selectOption('Minor')
 await expect(events).toHaveCount(1)
 await expect(events.first()).toContainText('Flood Advisory')
 await page.getByLabel('Relief severity',{exact:true}).selectOption('')
 await page.getByLabel('What should the plan cover?').fill('Florida flooding: accessible transport and 72-hour response')
 await page.getByRole('button',{name:'Generate detailed relief plan',exact:true}).click()
 await expect(page.getByRole('region',{name:'Generated relief plan'})).toContainText('First six hours')
 expect(input?.alertIds).toEqual(['fl-severe','fl-minor'])
 expect(input?.request).toContain('Florida flooding')
 await expect(page.getByRole('button',{name:'Download plan'})).toBeVisible()
 await page.screenshot({path:'test-results/relief-plan-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
test('map keeps simple disaster, geography and severity controls; relief failure is explicit',async({page})=>{
 await page.goto('/map',{waitUntil:'domcontentloaded'})
 await expect(page.getByLabel('Disaster type')).toBeVisible()
 await expect(page.getByLabel('Severity',{exact:true})).toBeVisible()
 await expect(page.getByText('Community needs & advanced filters',{exact:true})).toBeVisible()
 await expect(page.locator('.simple-advanced')).not.toHaveAttribute('open','')
 await page.route('**/api/public/alerts',r=>r.fulfill({json:{status:'available',data:{alerts,truncated:false},retrievedAt:'2026-11-07T20:00:00Z'}}))
 await page.route('**/api/relief/plan',r=>r.fulfill({status:503,json:{error:'Gemini unavailable. Please retry.'}}))
 await page.goto('/relief',{waitUntil:'domcontentloaded'})
 await page.getByRole('button',{name:'Generate detailed relief plan',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Gemini unavailable')
 await expect(page.getByRole('region',{name:'Generated relief plan'})).toHaveCount(0)
})
